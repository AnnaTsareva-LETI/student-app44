def fmt(x, digits=6):
    """Форматирование чисел."""
    if x == 0:
        return "0"
    if abs(x) < 1e-4 or abs(x) >= 1e5:
        return f"{x:.{digits}e}"
    return f"{x:.{digits}f}".rstrip("0").rstrip(",")


